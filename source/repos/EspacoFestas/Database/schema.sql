COMMENT ON TABLE ADICIONAL IS 'Garçom, comida, decoração, etc.';
COMMENT ON COLUMN ADICIONAL.VALOR_VENDA IS 'O que se cobra do cliente.';
COMMENT ON COLUMN ADICIONAL.VALOR_CUSTO IS 'O que a empresa paga (ex.: o garçom).';
COMMENT ON COLUMN ADICIONAL.COBRA_POR_QUANTIDADE IS 'Se verdadeiro, total = quantidade × valor (RN04).';

CREATE TABLE SERVICO_ADICIONAL (
