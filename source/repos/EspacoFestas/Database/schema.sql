CREATE TABLE CLIENTE (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(120) NOT NULL,
    ENDERECO        VARCHAR(200),
    CIDADE          VARCHAR(80),
    UF              CHAR(2),
    TELEFONE        VARCHAR(20),
    CPF             VARCHAR(14),
    ATIVO           D_ATIVO
);
COMMENT ON TABLE CLIENTE IS 'Quem contrata o evento.';
COMMENT ON COLUMN CLIENTE.CPF IS 'Opcional; se preenchido, deve ser único e válido (RN01).';
COMMENT ON COLUMN CLIENTE.ATIVO IS 'Cliente com agendamento não é excluído, é inativado (RN02).';

CREATE UNIQUE INDEX UX_CLIENTE_CPF ON CLIENTE (CPF);
CREATE INDEX IX_CLIENTE_NOME ON CLIENTE (NOME);

CREATE TABLE SERVICO (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME            VARCHAR(100) NOT NULL,
    DESCRICAO       VARCHAR(500),
    ATIVO           D_ATIVO
);
COMMENT ON TABLE SERVICO IS 'Serviço principal (o espaço). Não guarda preço — ver SERVICO_FAIXA.';
COMMENT ON COLUMN SERVICO.ATIVO IS 'Serviço usado não é excluído, é inativado (RN02).';

CREATE TABLE SERVICO_FAIXA (
    ID              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    SERVICO_ID      INTEGER NOT NULL,
    NOME            VARCHAR(60) NOT NULL,
    VALOR           D_VALOR,
    ORDEM_EXIBICAO  SMALLINT DEFAULT 0 NOT NULL,
    ATIVO           D_ATIVO,
    CONSTRAINT FK_SERVICO_FAIXA_SERVICO FOREIGN KEY (SERVICO_ID) REFERENCES SERVICO (ID)
);
COMMENT ON TABLE SERVICO_FAIXA IS 'Faixas de preço de cada serviço (ex.: Seg a Qua, Fim de semana/Feriado, Promoção).';
COMMENT ON COLUMN SERVICO_FAIXA.ORDEM_EXIBICAO IS 'Ordem de exibição na tela e no catálogo.';
COMMENT ON COLUMN SERVICO_FAIXA.ATIVO IS 'Faixa usada em agendamento não é excluída, é inativada (RN02, RN03).';

CREATE INDEX IX_SERVICO_FAIXA_SERVICO ON SERVICO_FAIXA (SERVICO_ID);

CREATE TABLE ADICIONAL (
    ID                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOME                    VARCHAR(100) NOT NULL,
    DESCRICAO               VARCHAR(500),
